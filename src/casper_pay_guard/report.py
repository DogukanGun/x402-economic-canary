    A("")
    A("These are reported as computed. Nothing was tuned to close them.")
    A("")

    # -- 5. ablations ------------------------------------------------------
    if ablations:
        A("## 5. Table 1 — component ablation (previously unbacked)")
        A("")
        t1_f = ablations.get("table1_forecast", {}).get("rows", {})
        t1_o = ablations.get("table1_oracle", {}).get("rows", {})
        A("| configuration | paper P / R / PR-AUC | oracle cfg | forecast cfg |")
        A("|---|---|---|---|")
        for name, (p, r, a) in PAPER_TABLE1.items():
            o = t1_o.get(name)
            f = t1_f.get(name)
