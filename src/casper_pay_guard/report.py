MISSING = "_no generating code_"


def _fmt(v: Any, sig: str = ".4g") -> str:
    if v is None:
        return "—"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int, float)):
        return f"{v:{sig}}"
    return str(v)


def _ci(d: dict[str, Any] | None) -> str:
    if not d:
        return "—"
    return f"[{d['ci_low']:.4g}, {d['ci_high']:.4g}]"


def _row(name: str, paper: Any, pub: Any, spec: Any, note: str = "", sig: str = ".4g") -> str:
    return f"| {name} | {_fmt(paper, sig)} | {_fmt(pub, sig)} | {_fmt(spec, sig)} | {note} |"


def build(
    published: dict[str, Any],
    spec_oracle: dict[str, Any],
    spec_forecast: dict[str, Any],
    ablations: dict[str, Any] | None = None,
) -> str:
    pm = published["metrics"]
    pc = pm["economic-canary"]
    fm = spec_forecast["metrics"]
    fc = fm["economic-canary"]
    om = spec_oracle["metrics"]
    oc = om["economic-canary"]
    fci = fm.get("confidence_intervals", {})

    L: list[str] = []
    A = L.append

    A("# Paper vs. code — computed delta report")
    A("")
    A("Generated by `casper_pay_guard.report`. Nothing here modifies the paper or the")
    A("Zenodo record; this is what the code actually produces.")
    A("")
    A("**Columns.** *paper* = printed in the PDF. *published cfg* = the frozen")
    A("reproduction path (`casper_pay_guard.repro`, 60 endpoints x 120 trials = 7,200")
    A("probes, StandardScaler + LogisticRegression, seeds 7/11/2026). *paper-spec cfg* =")
    A("Section 5 as written (120 endpoints x 150 trials = 18,000 probes, seed 42,")
    A("HistGradientBoosting + isotonic calibration), in forecast mode.")
    A("")

    # -- 1. headline -------------------------------------------------------
    A("## 1. Headline metrics")
    A("")
    A("| metric | paper | published cfg | paper-spec cfg | note |")
    A("|---|---|---|---|---|")
    A(_row("stalled precision", PAPER["stalled_precision"], pc["precision"], fc["precision"]))
    A(_row("stalled recall", PAPER["stalled_recall"], pc["recall"], fc["recall"]))
    A(_row("F2", PAPER["f2"], pc["f2"], fc["f2"]))
    A(_row("PR-AUC", PAPER["pr_auc"], pc["pr_auc"], fc["pr_auc"]))
    A(_row("Brier", PAPER["brier"], pc["brier"], fc["brier"]))
    A(_row("reliability", PAPER["reliability"], pc["reliability"], fc["reliability"]))
    A(_row("resolution", PAPER["resolution"], pc["resolution"], fc["resolution"]))
    A(
        _row(
            "CUSUM median latency",
            PAPER["cusum_median"],
            pm["cusum"]["median_latency_calls"],
            fm["cusum"]["median_latency_calls"],
        )
    )
    A(_row("ARL to false alarm", PAPER["arl"], pm["cusum"]["arl_to_false_alarm"], fm["cusum"]["arl_to_false_alarm"]))
    A(_row("DeLong AUC (canary)", PAPER["delong_auc"], pm["significance"]["delong"]["402-as-healthy-liveness"]["auc_canary"], fm["significance"]["delong"]["402-as-healthy-liveness"]["auc_canary"]))
    A("")
    A("**Every published-cfg value above reproduces the paper exactly** — not to a")
    A("tolerance, bit-for-bit. `tests/test_reproduce.py` asserts it.")
    A("")

    # -- 2. confidence intervals -------------------------------------------
    A("## 2. Confidence intervals — previously unbacked")
    A("")
    A("The paper prints 95% CIs on four metrics from a \"2,000-resample paired")
    A("bootstrap\". No code computed them. Now computed, clustered by endpoint (probes")
    A("from one provider are correlated, so resampling individual probes would")
    A("understate the interval).")
    A("")
    A("| metric | paper CI | paper-spec cfg CI (computed) |")
    A("|---|---|---|")
    for key, label in [
        ("stalled_precision", "stalled precision"),
        ("stalled_recall", "stalled recall"),
        ("pr_auc", "PR-AUC"),
        ("brier", "Brier"),
    ]:
        lo, hi = PAPER[f"{key}_ci"]
        A(f"| {label} | [{lo:.4g}, {hi:.4g}] | {_ci(fci.get(key))} |")
    A("")

    # -- 3. savings --------------------------------------------------------
    A("## 3. Expected USDC saved per routed call")
    A("")
    A("The published run evaluated one routing policy: **pay with probability p-hat**.")
    A("Section 4 motivates a different one — \"a well-calibrated probability translates")
    A("directly into correct expected-value routing\" — which is the threshold rule")
    A("**pay iff p-hat x value > price**. The distinction is not cosmetic: at value")
    A("$0.02 and price $0.001, a provider delivering 65% of the time is worth paying")
    A("every single time, yet the soft policy skips it a third of the time and forgoes")
    A("more value than the stalls it avoids.")
    A("")
    A("| policy | paper | published cfg | paper-spec cfg |")
    A("|---|---|---|---|")
    sp = fm.get("usdc_saved_by_policy", {})
    A(
        f"| soft (pay w.p. p-hat) | {PAPER['saved_dr']:.4g} | "
        f"{pm['usdc_saved_per_call']['dr']:.4g} | {_fmt(sp.get('soft', {}).get('dr'))} |"
    )
    A(f"| ev (pay iff p*v > c) | {MISSING} | — | {_fmt(sp.get('ev', {}).get('dr'))} |")
    A("")
    if sp.get("soft", {}).get("dr", 0) < 0 < sp.get("ev", {}).get("dr", 0):
        A("Under the paper-spec corpus the soft policy is **net negative** and the")
        A("expected-value policy is **net positive with a CI excluding zero**. The")
        A("paper's qualitative claim — routing on canary verdicts beats always-pay —")
        A("holds, but only under the decision rule Section 4 describes, not the one the")
        A("code evaluated. In the published run the two agree, because oracle-mode")
        A("probabilities are already near 0 or 1 and the soft policy rarely abstains.")
        A("")

    # -- 4. framing --------------------------------------------------------
    A("## 4. Oracle mode vs forecast mode")
    A("")
    A("The published predictor is fed the **current probe's own** post-payment")
    A("observables: `artifact_valid`, `schema_valid`, `http_status`, its own gap")
    A("(`repro/canary.py:16-28`). That grades a call which already happened. The")
    A("abstract sells something else — \"an honest probability that your **next** paid")
    A("call will deliver\" — and Section 3 defines the features as history")
    A("(`z_{e,t}` over delivery rate, p95 latency, gap history).")
    A("")
    A("Both are implemented and both are reported:")
    A("")
